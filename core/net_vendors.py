_BY_OUI = {oui: brand for brand, ouis in _PREFIXES.items() for oui in ouis}


def oui(mac):
    """'14:cc:20:aa:bb:cc' → '14CC20'. '' for an empty or random (locally administered) MAC."""
    h = ''.join(ch for ch in str(mac or '').upper() if ch in '0123456789ABCDEF')
    if len(h) < 6:
        return ''
    if int(h[1], 16) & 2:        # locally administered bit: phones randomise their MAC this way
        return ''
    return h[:6]


def brand_of(mac):
    """Maker of a network card from its MAC, or '' when it is not a router brand we know."""
    return _BY_OUI.get(oui(mac), '')


def is_random_mac(mac):
    h = ''.join(ch for ch in str(mac or '').upper() if ch in '0123456789ABCDEF')
    return len(h) >= 2 and bool(int(h[1], 16) & 2)

